import { medicineSchema as m } from "../../src/lib/validators/medicine.js";
import { invoiceSchema as i, invoiceItemSchema as it } from "../../src/lib/validators/invoice.js";
import { paymentSchema as p } from "../../src/lib/validators/payment.js";
let ok=0,bad=0; const t=(n,x)=>{x?ok++:(bad++,console.log("FAIL",n))};
const id="3481c58b-911d-4e5b-a0f9-366280cf0a11";
const med={name:"Paracetamol",description:"",stock_qty:"10",reorder_level:"5",unit_price:"2.50"};
t("med ok", m.safeParse(med).data?.unit_price===2.5);
t("med blank name", !m.safeParse({...med,name:" "}).success);
t("med neg stock", !m.safeParse({...med,stock_qty:"-1"}).success);
t("med decimal stock", !m.safeParse({...med,stock_qty:"1.5"}).success);
t("med 3-dec price", !m.safeParse({...med,unit_price:"1.234"}).success);
t("med price text", !m.safeParse({...med,unit_price:"abc"}).success);
t("inv ok no fee", i.safeParse({patient_id:id,appointment_id:"",notes:"",consultation_fee:""}).success);
t("inv ok fee", i.safeParse({patient_id:id,appointment_id:id,notes:"",consultation_fee:"500"}).data?.consultation_fee===500);
t("inv bad patient", !i.safeParse({patient_id:"x",appointment_id:"",notes:"",consultation_fee:""}).success);
t("inv bad appt", !i.safeParse({patient_id:id,appointment_id:"zz",notes:"",consultation_fee:""}).success);
t("inv neg fee", !i.safeParse({patient_id:id,appointment_id:"",notes:"",consultation_fee:"-5"}).success);
t("item ok", it.safeParse({description:"Lab",qty:"2",unit_price:"150.5"}).success);
t("item qty 0", !it.safeParse({description:"Lab",qty:"0",unit_price:"1"}).success);
t("item blank desc", !it.safeParse({description:" ",qty:"1",unit_price:"1"}).success);
t("pay ok", p.safeParse({amount:"200",method:"gcash",reference_no:""}).data?.amount===200);
t("pay zero", !p.safeParse({amount:"0",method:"cash",reference_no:""}).success);
t("pay neg", !p.safeParse({amount:"-1",method:"cash",reference_no:""}).success);
t("pay bad method", !p.safeParse({amount:"5",method:"bitcoin",reference_no:""}).success);
t("pay sql-ish amount", !p.safeParse({amount:"1; drop table x",method:"cash",reference_no:""}).success);
console.log(ok,"pass",bad,"fail");
