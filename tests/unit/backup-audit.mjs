import { parseBackup, RESTORE_TABLES, BACKUP_TABLES } from "../../src/lib/utils/backup.js";
import { changedFields, shortId, displayValue } from "../../src/lib/utils/audit.js";
import { auditQuerySchema as q } from "../../src/lib/validators/audit.js";
let ok=0,bad=0; const t=(n,x)=>{x?ok++:(bad++,console.log("FAIL",n))};
const mkTables=()=>Object.fromEntries(BACKUP_TABLES.map(k=>[k,[{id:"1"}]]));
const file=(o={})=>JSON.stringify({app:"CareNova",format_version:1,created_at:"2026-11-07T00:00:00Z",tables:mkTables(),...o});
let r=parseBackup(file());
t("valid backup parses", !r.error && Object.keys(r.tables).length===8);
t("profiles/doctors are not passed to restore", !("profiles" in r.tables) && !("doctors" in r.tables));
t("counts", r.counts.patients===1 && r.createdAt==="2026-11-07T00:00:00Z");
t("not json", /not valid JSON/.test(parseBackup("{oops").error));
t("array root", !!parseBackup("[]").error);
t("null root", !!parseBackup("null").error);
t("wrong app", /not a CareNova/.test(parseBackup(file({app:"Other"})).error));
t("wrong version", /different version/.test(parseBackup(file({format_version:2})).error));
t("no tables", /no table data/.test(parseBackup(file({tables:null})).error));
t("tables as array", !!parseBackup(file({tables:[]})).error);
const miss=mkTables(); delete miss.payments;
t("missing table names it", /payments/.test(parseBackup(file({tables:miss})).error));
const notarr=mkTables(); notarr.patients={};
t("table not array", /patients/.test(parseBackup(file({tables:notarr})).error));
const badrow=mkTables(); badrow.medicines=[1];
t("invalid row", /medicines/.test(parseBackup(file({tables:badrow})).error));
const nullrow=mkTables(); nullrow.medicines=[null];
t("null row", !!parseBackup(file({tables:nullrow})).error);
const big=mkTables(); big.patients=new Array(200001).fill({id:"x"});
t("too many rows", /too large/.test(parseBackup(file({tables:big})).error));
t("empty tables allowed", !parseBackup(file({tables:Object.fromEntries(BACKUP_TABLES.map(k=>[k,[]]))})).error);
// audit helpers
const c=changedFields({id:"1",name:"A",updated_at:"x",qty:1},{id:"1",name:"B",updated_at:"y",qty:1});
t("changedFields ignores updated_at and unchanged", c.length===1 && c[0].key==="name" && c[0].from==="A" && c[0].to==="B");
t("changedFields null safe", changedFields(null,{a:1}).length===0);
t("changedFields added key", changedFields({a:1},{a:1,b:2}).length===1);
t("shortId", shortId("abcdef0123456789")==="abcdef01" && shortId(null)==="-");
t("displayValue", displayValue(null)==="null" && displayValue({a:1})==='{"a":1}' && displayValue(5)==="5");
// audit query validation
const base={user:"",action:"",table:"",from:"",to:""};
t("q empty ok", q.safeParse(base).success);
t("q good", q.safeParse({user:"ana",action:"LOGIN",table:"patients",from:"2026-11-01",to:"2026-11-30"}).success);
t("q bad action", !q.safeParse({...base,action:"DROP"}).success);
t("q bad table", !q.safeParse({...base,table:"auth.users"}).success);
t("q bad date", !q.safeParse({...base,from:"2026-99-99"}).success);
t("q reversed", !q.safeParse({...base,from:"2026-11-30",to:"2026-11-01"}).success);
t("q long user", !q.safeParse({...base,user:"x".repeat(101)}).success);
console.log(ok,"pass",bad,"fail");
