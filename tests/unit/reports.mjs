import { toCsv } from "../../src/lib/utils/csv.js";
import { fillDays, fillMonths } from "../../src/lib/utils/charts.js";
import { reportQuerySchema as q } from "../../src/lib/validators/report.js";
let ok=0,bad=0; const t=(n,x)=>{x?ok++:(bad++,console.log("FAIL",n))};
const cols=[{key:"a",header:"A"},{key:"b",header:"B, with comma"}];
const csv=toCsv(cols,[{a:"=HYPERLINK(\"x\")",b:"plain"},{a:"-5",b:"+cmd|' /C calc'!A0"},{a:"He said \"hi\"",b:"line1\nline2"},{a:"@SUM(1)",b:null},{a:"Juan, Jr.",b:"100.50"}]);
t("BOM", csv.charCodeAt(0)===0xFEFF);
t("header quoted", csv.includes('A,"B, with comma"'));
t("formula neutralised =", csv.includes("'=HYPERLINK"));
t("negative number kept as number", csv.includes("\r\n-5,"));
t("+ formula neutralised", csv.includes("'+cmd"));
t("@ neutralised", csv.includes("'@SUM(1)"));
t("quotes escaped", csv.includes('"He said ""hi"""'));
t("newline quoted", csv.includes('"line1\nline2"'));
t("comma quoted", csv.includes('"Juan, Jr."'));
t("CRLF endings", csv.endsWith("\r\n"));
const d=fillDays([{day:"2026-11-07",total:3},{day:"2026-11-01",total:1}],"2026-11-07");
t("fillDays length 14", d.length===14);
t("fillDays today value 3 at index 6", d[6].value===3 && d[6].label==="Nov 7");
t("fillDays first day Nov 1 =1", d[0].label==="Nov 1" && d[0].value===1);
t("fillDays month rollover", fillDays([], "2026-12-31")[13].label==="Jan 7");
const m=fillMonths([{month:"2026-11",revenue:"502.50"},{month:"2026-06",revenue:"10"}],"2026-11-07");
t("fillMonths 6 entries", m.length===6 && m[5].label==="Nov 26" && m[5].value===502.5);
t("fillMonths oldest Jun", m[0].label==="Jun 26" && m[0].value===10);
t("fillMonths year rollover", fillMonths([], "2026-02-10")[0].label==="Sep 25");
t("q ok", q.safeParse({type:"daily_collection",from:"2026-11-01",to:"2026-11-30"}).success);
t("q empty dates ok", q.safeParse({type:"low_stock",from:"",to:""}).success);
t("q bad type", !q.safeParse({type:"drop_table",from:"",to:""}).success);
t("q bad date", !q.safeParse({type:"low_stock",from:"2026-13-45",to:""}).success);
t("q injection date", !q.safeParse({type:"low_stock",from:"2026-11-01'; drop",to:""}).success);
t("q reversed range", !q.safeParse({type:"daily_collection",from:"2026-11-30",to:"2026-11-01"}).success);
console.log(ok,"pass",bad,"fail");
